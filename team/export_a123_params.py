#!/usr/bin/env python3
"""
Export the A123 ESC cell model from sim-PCM-SCM-python into a JSON file.

Usage:
    python3 export_a123_params.py <path to sim-PCM-SCM-python-main> [out.json]

Why: A123modeldyn.pickle needs numpy/pandas and the repo's models.py to load.
The BMS prototype should not depend on that, so we export the numbers once.

Provenance: the pickle was generated by esctoolbox-python (a Python port of
Plett's ESC toolbox) from A123 cell lab data. Plett's original MATLAB toolbox:
http://mocha-java.uccs.edu/BMS1/

Units / conventions (Plett ESC model, discharge current positive):
    temps  deg C          Q    Ah        eta  coulombic efficiency (charge)
    R0, R1 ohm (per cell)  RC   s   <- stored value is used as the time constant
                                        in seconds (RCfact = exp(-dT/|RC|)), which
                                        is Plett's convention, verified against
                                        esctoolbox-python (processDynamic:
                                        RCfact = exp(-dT/|RC|), dT in s).
    M0, M  V hysteresis    G    hysteresis rate constant
    ocv(soc, T) = ocv0(soc) + T * ocvrel(soc)
"""
import json
import os
import pickle
import sys

import numpy as np


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    repo = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "a123_params.json"
    sys.path.insert(0, repo)
    import models                                   # repo's ModelDyn class
    sys.modules["__main__"].ModelDyn = models.ModelDyn
    with open(os.path.join(repo, "A123modeldyn.pickle"), "rb") as f:
        m = pickle.load(f)

    flat = lambda a: [round(float(x), 7) for x in np.ravel(a)]
    data = {
        "_source": "A123modeldyn.pickle from sim-PCM-SCM-python (esctoolbox-python / Plett ESC)",
        "_note": "RC interpreted as seconds (Plett convention) - verified against esctoolbox-python. G=1.0 at 5-45C is the identification lower bound. See export_a123_params.py.",
        "temps": flat(m.temps),
        "Q": flat(m.QParam), "eta": flat(m.etaParam),
        "R0": flat(m.R0Param), "R1": flat(m.RParam), "RC": flat(m.RCParam),
        "M0": flat(m.M0Param), "M": flat(m.MParam), "G": flat(m.GParam),
        "soc": flat(m.SOC), "ocv0": flat(m.OCV0), "ocvrel": flat(m.OCVrel),
    }
    with open(out, "w") as f:
        json.dump(data, f)
    print(f"wrote {out}: {len(data['temps'])} temperatures, {len(data['soc'])} SOC points")


if __name__ == "__main__":
    main()
